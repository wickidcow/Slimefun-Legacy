package io.github.thebusybiscuit.slimefun4.core.guide.categories;

/**
 * Canonical high-level guide category ids shared with the Slimefun5 category model.
 *
 * <p>Slimefun Legacy keeps its classic ItemGroup-first guide layout, but addons may declare one of these ids on an
 * ItemGroup so every item in that group inherits the same searchable category.
 */
public final class DefaultGuideCategories {

    public static final String WEAPONS = "weapons";
    public static final String TOOLS = "tools";
    public static final String ARMOR = "armor";
    public static final String MACHINES = "machines";
    public static final String ENERGY_TECH = "energy_tech";
    public static final String RESOURCES = "resources";
    public static final String MAGIC = "magic";
    public static final String FOOD = "food";
    public static final String LOGISTICS = "logistics";
    public static final String DECORATION = "decoration";
    public static final String MISC = "misc";

    private DefaultGuideCategories() {}
}
